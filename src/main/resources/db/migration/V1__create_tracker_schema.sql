CREATE TABLE app_user (
    id UUID PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(120) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','DEVELOPER','TESTER','REPORTER')),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE project (
    id UUID PRIMARY KEY,
    project_key VARCHAR(12) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    game_title VARCHAR(120) NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE issue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES project(id),
    reporter_id UUID NOT NULL REFERENCES app_user(id),
    assignee_id UUID REFERENCES app_user(id),
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    reproduction_steps TEXT NOT NULL,
    expected_result TEXT NOT NULL,
    actual_result TEXT NOT NULL,
    game_version VARCHAR(64) NOT NULL,
    platform VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    priority VARCHAR(16) NOT NULL CHECK (priority IN ('LOW','NORMAL','HIGH','URGENT')),
    status VARCHAR(24) NOT NULL CHECK (status IN ('NEW','TRIAGED','IN_PROGRESS','READY_FOR_TEST','VERIFIED','CLOSED','REOPENED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    row_version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE issue_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES issue(id) ON DELETE CASCADE,
    author_id UUID NOT NULL REFERENCES app_user(id),
    body VARCHAR(5000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE issue_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES issue(id) ON DELETE CASCADE,
    old_status VARCHAR(24),
    new_status VARCHAR(24) NOT NULL,
    actor_id UUID NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX issue_project_state_updated_idx ON issue(project_id, status, updated_at DESC);
CREATE INDEX issue_project_priority_updated_idx ON issue(project_id, priority, updated_at DESC);
CREATE INDEX issue_comment_issue_created_idx ON issue_comment(issue_id, created_at);
CREATE INDEX issue_history_issue_created_idx ON issue_history(issue_id, created_at);

